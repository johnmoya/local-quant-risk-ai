"""The published M13 artefacts (results/volatility/m13/, M13.8) are a
regression test, under the two-level contract of docs/design_m13.md §2.

**Level A**, in the reference environment that ran M13.8: forecasts.csv,
evaluation.json and garch_fit_log.csv are regenerated byte for byte.
run_metadata.json is only pinned: it records when and where the run
happened, and is never regenerated.

**Level B**, everywhere else, by layer (decided at M13.9; measured on the
development machine with NPY_DISABLE_CPU_FEATURES="X86_V4 AVX512_ICL"):

1. **Exact:** every discrete value. That covers dates, exception
   indicators, counts, Basel zones (full, rolling, annual), test
   decisions, Holm significance, the H1-H4 verdicts and GARCH fit status
   and refit dates. W250 included: without AVX-512 none of these moved.
2. **Within MAX_ULPS:** every float that does not depend on arch (Naive,
   EWMA, FHS on them, the frozen series, regimes). Measured: 10 ulps.
3. **Within MAX_RELATIVE:** every float that depends on the primary GARCH
   fits. arch's optimiser turns a 1-ulp difference in the log returns
   into relative differences of at most 1.6e-6 (on a fitted omega).
4. **Not compared:** the floats that depend on the W250 GARCH fits,
   plus that schedule's fit log, params_date, stale columns and the
   `garch.w250` block. Three W250 refits converge on alpha + beta = 1, the
   edge of the pre-registered validity rule alpha + beta < 1:
   - 2020-04-01, one ulp below 1;
   - 2020-11-02, 5e-12 below 1;
   - 2020-12-01, 2.5e-13 below 1.

   All three are valid with AVX-512. Without it the first two land on 1
   or above and fail: 8 failures instead of 6, more stale days, and sigma²
   off by up to 30%. It is a reproducibility limit, pinned below, not a
   tolerance (docs/results_m13.md).
"""

