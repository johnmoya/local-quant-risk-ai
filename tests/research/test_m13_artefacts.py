def test_level_b_tolerates_the_measured_w250_garch_change():
    """What changed without AVX-512, and only that, passes."""
    committed = json.loads(_committed("evaluation.json"))
    produced = json.loads(_committed("evaluation.json"))
    produced["garch"]["w250"].update(n_failed=8, stale_days=169, n_near_igarch=1)
    produced["garch"]["w250"]["failed_refits"].append("2020-04-01")
    produced["volatility"]["garch_w250"]["qlike"] *= 1.01
    produced["diebold_mariano"]["F2_w250"]["ewma_vs_naive_fhs_w250"]["holm_adjusted_p"] *= 1.1
    assert json_level_b(committed, produced) == []
