def test_level_b_float_bounds_are_exact():
    committed = _committed("forecasts.csv")
    at = _edit_csv("forecasts.csv", 1000, "ewma_fhs_primary_var", lambda v: _ulps_up(v, MAX_ULPS))
    beyond = _edit_csv(
        "forecasts.csv", 1000, "ewma_fhs_primary_var", lambda v: _ulps_up(v, MAX_ULPS + 1)
    )
    assert csv_level_b("forecasts.csv", committed, at) == []
    assert len(csv_level_b("forecasts.csv", committed, beyond)) == 1

    def scaled(factor: float) -> Callable[[str], str]:
        return lambda v: repr(float(v) * factor)

    within = _edit_csv(
        "forecasts.csv", 1000, "garch_normal_primary_var", scaled(1 + 0.9 * MAX_RELATIVE)
    )
    outside = _edit_csv(
        "forecasts.csv", 1000, "garch_normal_primary_var", scaled(1 + 1.1 * MAX_RELATIVE)
    )
    assert csv_level_b("forecasts.csv", committed, within) == []
    assert len(csv_level_b("forecasts.csv", committed, outside)) == 1


