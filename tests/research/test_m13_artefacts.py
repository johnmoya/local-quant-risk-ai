# Measured without AVX-512 on the development machine, with the
# comparators below:
# - 10 ulps on the arch-free floats. The forecasts and losses differ by
#   at most 4. The 10 are Diebold-Mariano statistics of near-equal losses,
#   e.g. naive_fhs_w250 vs naive_normal_w250, whose mean difference
#   (4e-6) is ~1% of the losses, so the subtraction amplifies the input
#   ulps.
# - 3.9e-7 relative on the primary-GARCH floats; 1.59e-6 on a CI Python
#   3.11 runner with X86_V3 (run 38322657855), on the omega of one
#   primary refit in the fit log, while its forecasts and evaluation stayed
#   within 1.2e-6.
# Bounds ~3x, as for the baseline. If a new environment exceeds them,
# measure there and record the figure before changing them; never widen
# them to quiet the suite.
MEASURED_MAX_ULPS = 10
MAX_ULPS = 30
MEASURED_MAX_RELATIVE = 1.59e-6
MAX_RELATIVE = 5e-6

# The declared W250 limit: the refits on the boundary alpha + beta = 1, and
# alpha + beta in the reference run. The first two fail without AVX-512.
BOUNDARY_REFITS = {
    "2020-04-01": math.nextafter(1.0, 0.0),
    "2020-11-02": 0.9999999999950024,
    "2020-12-01": 0.999999999999748,
}

EXACT, ULPS, RELATIVE, NOT_COMPARED = "exact", "ulps", "relative", "not compared"


# --- layers ---------------------------------------------------------------------------------


def _w250_garch(text: str) -> bool:
    return "garch" in text and "w250" in text


def csv_layer(file: str, column: str, row: dict[str, str], is_float: bool) -> str:
    if file == "garch_fit_log.csv":
        if row["schedule"] == "w250":
            return NOT_COMPARED
        return RELATIVE if is_float else EXACT
    if column in ("garch_w250_params_date", "garch_w250_stale"):
        return NOT_COMPARED
    if not is_float:
        return EXACT
    if _w250_garch(column):
        return NOT_COMPARED
    return RELATIVE if "garch" in column else ULPS


def json_layer(path: tuple[str, ...], context: str, is_float: bool) -> str:
    if path[:2] == ("garch", "w250"):
        return NOT_COMPARED
    if not is_float:
        return EXACT
    family = path[1] if path[0] == "diebold_mariano" else ""
    if path[0] == "spearman_qlike_vs_quantile_loss":
        # Every rho ranks series that include GARCH W250.
        return NOT_COMPARED
    if path[-1] == "holm_adjusted_p" and family.endswith("_w250"):
        return NOT_COMPARED  # the family's adjustment involves W250 GARCH p-values
    if _w250_garch(context):
        return NOT_COMPARED
    if path[-1] == "holm_adjusted_p" or "garch" in context:
        return RELATIVE
    return ULPS


def _json_leaves(value: object, path: tuple[str, ...] = (), context: str = "") -> Iterator:
    if isinstance(value, dict):
        # The series an entry is about, where it names one (decomposition
        # rows, DM entries); only string values, never a whole sub-block.
        named = " ".join(
            value[k]
            for k in ("series", "a", "b", "volatility_model")
            if isinstance(value.get(k), str)
        )
        for key, item in value.items():
            yield from _json_leaves(item, (*path, str(key)), f"{context} {named} {key}")
    elif isinstance(value, list):
        for i, item in enumerate(value):
            yield from _json_leaves(item, (*path, str(i)), context)
    else:
        yield path, context, value


def _csv_cells(text: str) -> Iterator[tuple[int, dict[str, str], str, str]]:
    for i, row in enumerate(csv.DictReader(io.StringIO(text))):
        for column, value in row.items():
            yield i, row, column, value


def _is_float_text(value: str) -> bool:
    try:
        float(value)
    except ValueError:
        return False
    return any(c in value for c in ".en")  # ints and booleans are discrete


def _relative(a: float, b: float) -> float:
    if a == b:
        return 0.0
    return abs(a - b) / max(abs(a), abs(b))


def _compare(
    layer: str, expected: object, actual: object, where: str, gaps: dict[str, float]
) -> list[str]:
    if layer == NOT_COMPARED:
        return []
    both_nan = (
        isinstance(expected, float)
        and isinstance(actual, float)
        and math.isnan(expected)
        and math.isnan(actual)
    )
    if both_nan:
        return []
    if layer == EXACT or not isinstance(expected, float) or not isinstance(actual, float):
        if type(expected) is not type(actual) or expected != actual:
            return [f"{where}: {expected!r} != {actual!r} (must be identical)"]
        return []
    if math.isnan(expected) or math.isnan(actual):
        return [f"{where}: NaN mismatch"]
    if layer == ULPS:
        ulps = ulps_between(expected, actual)
        gaps[ULPS] = max(gaps[ULPS], ulps)
        return [] if ulps <= MAX_ULPS else [f"{where}: {ulps} ulps"]
    relative = _relative(expected, actual)
    gaps[RELATIVE] = max(gaps[RELATIVE], relative)
    return [] if relative <= MAX_RELATIVE else [f"{where}: relative {relative:.3g}"]


def csv_level_b(
    file: str, committed: str, produced: str, gaps: dict[str, float] | None = None
) -> list[str]:
    gaps = gaps if gaps is not None else {ULPS: 0.0, RELATIVE: 0.0}
    first = committed.splitlines()[:1]
    if first != produced.splitlines()[:1]:
        return ["header differs"]
    a, b = list(_csv_cells(committed)), list(_csv_cells(produced))
    if len(a) != len(b):
        return ["row count differs"]
    out: list[str] = []
    for (i, row, column, x), (_, _, _, y) in zip(a, b, strict=True):
        is_float = _is_float_text(x) and _is_float_text(y)
        layer = csv_layer(file, column, row, is_float)
        expected: object = float(x) if is_float else x
        actual: object = float(y) if is_float else y
        out += _compare(layer, expected, actual, f"{file} row {i} {column}", gaps)
    return out


def json_level_b(
    committed: dict, produced: dict, gaps: dict[str, float] | None = None
) -> list[str]:
    gaps = gaps if gaps is not None else {ULPS: 0.0, RELATIVE: 0.0}
    a, b = list(_json_leaves(committed)), list(_json_leaves(produced))
    if [p for p, _, _ in a] != [p for p, _, _ in b]:
        # Structure differs: only allowed inside the not-compared block.
        strip = [[p for p, _, _ in leaves if p[:2] != ("garch", "w250")] for leaves in (a, b)]
        if strip[0] != strip[1]:
            return ["keys or lengths differ"]
        a = [leaf for leaf in a if leaf[0][:2] != ("garch", "w250")]
        b = [leaf for leaf in b if leaf[0][:2] != ("garch", "w250")]
    out: list[str] = []
    for (path, context, x), (_, _, y) in zip(a, b, strict=True):
        layer = json_layer(path, context, isinstance(x, float) and isinstance(y, float))
        out += _compare(layer, x, y, "$." + ".".join(path), gaps)
    return out[:20]


# --- regeneration ---------------------------------------------------------------------------


@pytest.fixture(scope="module")
def regenerated(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """What run_m13.main computes, without its single-run guard."""
    output = tmp_path_factory.mktemp("m13") / "m13"
    config = M13Config()
    returns = load_spliced_returns().returns.returns
    walk_forward = run_walk_forward(returns, config)
    frozen = load_frozen_baseline(BASELINE_CSV, walk_forward.frame["date"])
    evaluation = Evaluation(walk_forward, frozen, returns, config).build()
    write_outputs(walk_forward, evaluation, output)
    return output


def _committed(name: str) -> str:
    return (COMMITTED / name).read_text(encoding="utf-8")


@pytest.mark.parametrize("name", list(COMMITTED_SHA256))
def test_the_published_m13_files_are_unchanged(name: str):
    assert sha256((COMMITTED / name).read_bytes()) == COMMITTED_SHA256[name]


def test_run_metadata_records_the_run():
    metadata = json.loads(_committed("run_metadata.json"))
    assert metadata["git_commit"] == "e3121fc58eec08e0f21478f7807e8c27c2619ed9"
    assert metadata["preregistration_commit"] == PREREGISTRATION_COMMIT
    environment = metadata["environment"]
    assert environment["python"].startswith(REFERENCE.python + ".")
    assert (environment["numpy"], environment["scipy"], environment["pandas"]) == (
        REFERENCE.numpy,
        REFERENCE.scipy,
        REFERENCE.pandas,
    )
    assert environment["numpy_log_dispatch"] == REFERENCE.log_dispatch


@pytest.mark.parametrize("name", REGENERATED)
def test_level_a_byte_for_byte(name: str, regenerated: Path):
    require_level_a(REFERENCE)
    committed = (COMMITTED / name).read_bytes()
    produced = (regenerated / name).read_bytes()
    assert sha256(produced) == sha256(committed), first_byte_difference(committed, produced)


